# Project: IdeaSprint
def print_scenarios():
    """
    Сценарии использования IdeaSprint:
    1. Пользователь регистрируется и получает уникальный ID.
    2. Создаётся гипотеза с описанием, метрикой успеха и оценкой.
    3. Гипотеза публикуется на доске для голосования.
    4. Пользователи голосуют за гипотезы (поднимают руку).
    5. По достижении порога голосов гипотеза превращается в задачу.
    6. Задача делегируется команде с назначением ответственного.
    7. Команда выполняет задачу, вносит изменения в репозиторий.
    8. При успешном завершении задача помечается как завершённая.
    9. Завершённая задача автоматически превращается в результат.
    10. Результат публикуется на доске с описанием и метрикой.
    11. Пользователь может комментировать любую сущность.
    12. Пользователь может редактировать или удалять свои записи.
    13. Система генерирует отчёт по всем сценариям.
    """
    scenarios = [
        "Регистрация и аутентификация",
        "Создание и публикация гипотезы",
        "Голосование за гипотезы",
        "Превращение гипотезы в задачу",
        "Делегирование задачи команде",
        "Выполнение задачи командой",
        "Превращение задачи в результат",
        "Публикация результата на доске",
        "Комментирование записей",
        "Редактирование и удаление записей",
        "Генерация отчёта по сценариям",
    ]
    print("Сценарии использования IdeaSprint:")
    for i, scenario in enumerate(scenarios, 1):
        print(f"{i}. {scenario}")
    print(f"Всего сценариев: {len(scenarios)}")
